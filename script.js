// Elementos do HTML
const languageSelector = document.getElementById("language");
const yearElement = document.getElementById("year");


// Atualizar os textos
function setLanguage(language) {

    // Verifica se o idioma existe
    if (!translations[language]) {
        language = "pt";
    }

    // Atualiza o idioma da página
    document.documentElement.lang = language;

    // Percorre todos os elementos com data-i18n
    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.dataset.i18n;

        // Verifica se existe tradução para o elemento
        if (translations[language][key]) {
            element.innerHTML = translations[language][key];
        }

    });

    // Atualiza o seletor
    if (languageSelector) {
        languageSelector.value = language;
    }

    // Guarda o idioma escolhido
    localStorage.setItem("portfolio-language", language);
}


// Evento de mudança de idioma
if (languageSelector) {
    languageSelector.addEventListener("change", event => {
        setLanguage(event.target.value);
    });
}


// Atualiza automaticamente o ano
if (yearElement) {
    yearElement.textContent = new Date().getFullYear();
}


// Carrega o idioma guardado ou Português por defeito
const savedLanguage = localStorage.getItem("portfolio-language") || "pt";

setLanguage(savedLanguage);
